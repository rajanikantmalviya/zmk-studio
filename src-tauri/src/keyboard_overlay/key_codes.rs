pub fn usage_from_windows_key(virtual_key: u32, scan: u32, extended: bool) -> Option<u32> {
    let consumer = match virtual_key {
        0xad => Some(0xe2),
        0xae => Some(0xea),
        0xaf => Some(0xe9),
        0xb0 => Some(0xb5),
        0xb1 => Some(0xb6),
        0xb2 => Some(0xb7),
        0xb3 => Some(0xcd),
        0xa6 => Some(0x224),
        0xa7 => Some(0x225),
        0xa8 => Some(0x227),
        0xa9 => Some(0x226),
        0xaa => Some(0x221),
        0xab => Some(0x22a),
        0xac => Some(0x223),
        _ => None,
    };
    if let Some(id) = consumer {
        return Some(0xc0000 | id);
    }
    if (0x70..=0x7b).contains(&virtual_key) {
        return Some(0x70000 | (0x3a + virtual_key - 0x70));
    }
    if (0x7c..=0x87).contains(&virtual_key) {
        return Some(0x70000 | (0x68 + virtual_key - 0x7c));
    }
    if virtual_key == 0x13 {
        return Some(0x70048);
    }
    if virtual_key == 0x90 {
        return Some(0x70053);
    }
    if virtual_key == 0x92 {
        return Some(0x70067);
    }
    let id = if extended {
        match scan {
            0x1c => 0x58,
            0x1d => 0xe4,
            0x35 => 0x54,
            0x37 => 0x46,
            0x38 => 0xe6,
            0x47 => 0x4a,
            0x48 => 0x52,
            0x49 => 0x4b,
            0x4b => 0x50,
            0x4d => 0x4f,
            0x4f => 0x4d,
            0x50 => 0x51,
            0x51 => 0x4e,
            0x52 => 0x49,
            0x53 => 0x4c,
            0x5b => 0xe3,
            0x5c => 0xe7,
            0x5d => 0x65,
            _ => return None,
        }
    } else {
        match scan {
            0x01 => 0x29,
            0x02..=0x0a => 0x1e + scan - 0x02,
            0x0b => 0x27,
            0x0c => 0x2d,
            0x0d => 0x2e,
            0x0e => 0x2a,
            0x0f => 0x2b,
            0x10 => 0x14,
            0x11 => 0x1a,
            0x12 => 0x08,
            0x13 => 0x15,
            0x14 => 0x17,
            0x15 => 0x1c,
            0x16 => 0x18,
            0x17 => 0x0c,
            0x18 => 0x12,
            0x19 => 0x13,
            0x1a => 0x2f,
            0x1b => 0x30,
            0x1c => 0x28,
            0x1d => 0xe0,
            0x1e => 0x04,
            0x1f => 0x16,
            0x20 => 0x07,
            0x21 => 0x09,
            0x22 => 0x0a,
            0x23 => 0x0b,
            0x24 => 0x0d,
            0x25 => 0x0e,
            0x26 => 0x0f,
            0x27 => 0x33,
            0x28 => 0x34,
            0x29 => 0x35,
            0x2a => 0xe1,
            0x2b => 0x31,
            0x2c => 0x1d,
            0x2d => 0x1b,
            0x2e => 0x06,
            0x2f => 0x19,
            0x30 => 0x05,
            0x31 => 0x11,
            0x32 => 0x10,
            0x33 => 0x36,
            0x34 => 0x37,
            0x35 => 0x38,
            0x36 => 0xe5,
            0x37 => 0x55,
            0x38 => 0xe2,
            0x39 => 0x2c,
            0x3a => 0x39,
            0x3b..=0x44 => 0x3a + scan - 0x3b,
            0x45 => 0x53,
            0x46 => 0x47,
            0x47 => 0x5f,
            0x48 => 0x60,
            0x49 => 0x61,
            0x4a => 0x56,
            0x4b => 0x5c,
            0x4c => 0x5d,
            0x4d => 0x5e,
            0x4e => 0x57,
            0x4f => 0x59,
            0x50 => 0x5a,
            0x51 => 0x5b,
            0x52 => 0x62,
            0x53 => 0x63,
            0x56 => 0x64,
            0x57 => 0x44,
            0x58 => 0x45,
            _ => return None,
        }
    };
    Some(0x70000 | id)
}

#[cfg(test)]
mod tests {
    use super::usage_from_windows_key as usage;

    #[test]
    fn distinguishes_navigation_modifiers_and_numpad() {
        assert_eq!(usage(0x41, 0x1e, false), Some(0x70004));
        assert_eq!(usage(0, 0x1d, false), Some(0x700e0));
        assert_eq!(usage(0, 0x1d, true), Some(0x700e4));
        assert_eq!(usage(0, 0x1c, false), Some(0x70028));
        assert_eq!(usage(0, 0x1c, true), Some(0x70058));
        assert_eq!(usage(0, 0x47, false), Some(0x7005f));
        assert_eq!(usage(0, 0x47, true), Some(0x7004a));
        assert_eq!(usage(0, 0x5c, true), Some(0x700e7));
    }

    #[test]
    fn supports_consumer_function_and_special_keys() {
        assert_eq!(usage(0xad, 0, false), Some(0xc00e2));
        assert_eq!(usage(0xb3, 0, false), Some(0xc00cd));
        assert_eq!(usage(0x13, 0x45, false), Some(0x70048));
        assert_eq!(usage(0x87, 0, false), Some(0x70073));
        assert_eq!(usage(0, 0xff, true), None);
    }
}
